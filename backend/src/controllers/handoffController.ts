import { Request, Response } from 'express';

function extractSection(text: string, tag: string): string | null {
  const regex = new RegExp(`---BEGIN FOYC ${tag}---([\\s\\S]*?)---END FOYC ${tag}---`, 'i');
  const match = text.match(regex);
  return match ? match[1].trim() : null;
}

export const importHandoff = async (req: Request, res: Response): Promise<void> => {
  const { rawHandoffText, userProfile, userReflection } = req.body;

  // 1. Payload size protection (500KB limit)
  if (!rawHandoffText || typeof rawHandoffText !== 'string') {
    res.status(400).json({ success: false, error: 'Handoff text content is required.' });
    return;
  }

  if (rawHandoffText.length > 500000) {
    res.status(413).json({ success: false, error: 'Handoff text exceeds maximum allowed size (500KB).' });
    return;
  }

  // 2. Check for FOYC_DASHBOARD_START JSON format
  let startIdx = rawHandoffText.indexOf('FOYC_DASHBOARD_START');
  let endIdx = rawHandoffText.indexOf('FOYC_DASHBOARD_END');

  if (startIdx === -1 || endIdx === -1) {
    startIdx = rawHandoffText.indexOf('FOYC_HANDOFF_START');
    endIdx = rawHandoffText.indexOf('FOYC_HANDOFF_END');
  }

  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const jsonStr = rawHandoffText.slice(startIdx + (rawHandoffText.includes('FOYC_DASHBOARD_START') ? 'FOYC_DASHBOARD_START'.length : 'FOYC_HANDOFF_START'.length), endIdx).trim();
    try {
      const parsedJson = JSON.parse(jsonStr);
      res.json({
        success: true,
        format: 'canonical_json_v2',
        parsedData: parsedJson,
        message: 'Canonical FOYC Dashboard JSON parsed and validated successfully.',
      });
      return;
    } catch (jsonErr: any) {
      res.status(422).json({
        success: false,
        error: `JSON parsing failed: ${jsonErr?.message || 'Invalid JSON syntax'}. Ensure the content between markers is valid JSON.`,
      });
      return;
    }
  }

  // 3. Fallback: Validate legacy section markers
  const dirBlock = extractSection(rawHandoffText, 'CAREER DIRECTION');
  const milestonesBlock = extractSection(rawHandoffText, 'MILESTONES');
  const tasksBlock = extractSection(rawHandoffText, 'TASKS');
  const habitsBlock = extractSection(rawHandoffText, 'HABITS');

  if (!dirBlock && !tasksBlock && !milestonesBlock) {
    res.status(422).json({
      success: false,
      error: 'Invalid handoff format. Standard FOYC markers (FOYC_DASHBOARD_START ... FOYC_DASHBOARD_END) were not detected.',
      suggestion: 'Ensure you copied the entire message generated by ChatGPT including the start and end markers.',
    });
    return;
  }

  // 4. Parse Legacy Career Direction
  let primaryTitle = 'Custom Career Direction';
  let summary = 'A practical roadmap tailored to your strengths and ambitions.';
  let whyRecommended = 'Aligned with your self-reported problem solving preferences.';
  let longTermGoal = 'Achieve professional independence and market mastery.';
  let shortTermObjective = 'Master fundamental core competencies within 90 days.';
  const alternativeTitles: string[] = [];
  const strengths: string[] = [];
  const skillGaps: string[] = [];

  if (dirBlock) {
    const lines = dirBlock.split('\n').map((l) => l.trim()).filter(Boolean);
    for (const line of lines) {
      const lower = line.toLowerCase();
      if (lower.startsWith('primary:') || lower.startsWith('primary direction:') || lower.startsWith('primary career:')) {
        primaryTitle = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('summary:') || lower.startsWith('overview:')) {
        summary = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('why:') || lower.startsWith('reason:') || lower.startsWith('why recommended:')) {
        whyRecommended = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('long-term goal:') || lower.startsWith('long term:')) {
        longTermGoal = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('short-term objective:') || lower.startsWith('short term:')) {
        shortTermObjective = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('alternatives:') || lower.startsWith('alternative:')) {
        alternativeTitles.push(...line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, '')));
      } else if (lower.startsWith('strengths:')) {
        strengths.push(...line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, '')));
      } else if (lower.startsWith('skill gaps:') || lower.startsWith('gaps:')) {
        skillGaps.push(...line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, '')));
      }
    }
  }

  res.json({
    success: true,
    format: 'legacy_delimited_v1',
    parsedData: {
      direction: {
        primaryTitle,
        summary,
        whyRecommended,
        longTermGoal,
        shortTermObjective,
        alternativeTitles,
        strengths,
        skillGaps,
      },
    },
  });
};
