import { Request, Response } from 'express';

function extractSection(text: string, tag: string): string | null {
  const regex = new RegExp(`---BEGIN FOYC ${tag}---([\\s\\S]*?)---END FOYC ${tag}---`, 'i');
  const match = text.match(regex);
  return match ? match[1].trim() : null;
}

export const importHandoff = async (req: Request, res: Response): Promise<void> => {
  const { rawHandoffText, userProfile, userReflection } = req.body;

  // 1. Payload size protection (500KB limit)
  if (!rawHandoffText || typeof rawHandoffText !== 'string') {
    res.status(400).json({ success: false, error: 'Handoff text content is required.' });
    return;
  }

  if (rawHandoffText.length > 500000) {
    res.status(413).json({ success: false, error: 'Handoff text exceeds maximum allowed size (500KB).' });
    return;
  }

  // 2. Validate essential markers
  const dirBlock = extractSection(rawHandoffText, 'CAREER DIRECTION');
  const milestonesBlock = extractSection(rawHandoffText, 'MILESTONES');
  const tasksBlock = extractSection(rawHandoffText, 'TASKS');
  const habitsBlock = extractSection(rawHandoffText, 'HABITS');

  if (!dirBlock && !tasksBlock && !milestonesBlock) {
    res.status(422).json({
      success: false,
      error: 'Invalid handoff format. Standard FOYC section markers (e.g. ---BEGIN FOYC CAREER DIRECTION---) were not detected.',
      suggestion: 'Ensure you copied the entire message generated by ChatGPT after requesting your FOYC handoff.',
    });
    return;
  }

  // 3. Parse Career Direction
  let primaryTitle = 'Custom Career Direction';
  let summary = 'A practical roadmap tailored to your strengths and ambitions.';
  let whyRecommended = 'Aligned with your self-reported problem solving preferences.';
  let longTermGoal = 'Achieve professional independence and market mastery.';
  let shortTermObjective = 'Master fundamental core competencies within 90 days.';
  const alternativeTitles: string[] = [];
  const strengths: string[] = [];
  const skillGaps: string[] = [];

  if (dirBlock) {
    const lines = dirBlock.split('\n').map((l) => l.trim()).filter(Boolean);
    for (const line of lines) {
      const lower = line.toLowerCase();
      if (lower.startsWith('primary:') || lower.startsWith('primary direction:') || lower.startsWith('primary career:')) {
        primaryTitle = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('summary:') || lower.startsWith('overview:')) {
        summary = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('why:') || lower.startsWith('reason:') || lower.startsWith('why recommended:')) {
        whyRecommended = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('long-term goal:') || lower.startsWith('long term:')) {
        longTermGoal = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('short-term objective:') || lower.startsWith('short term:')) {
        shortTermObjective = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (lower.startsWith('alternatives:') || lower.startsWith('alternative:')) {
        alternativeTitles.push(...line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, '')));
      } else if (lower.startsWith('strengths:')) {
        strengths.push(...line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, '')));
      } else if (lower.startsWith('skill gaps:') || lower.startsWith('gaps:')) {
        skillGaps.push(...line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, '')));
      }
    }
  }

  // 4. Parse Milestones
  const milestones: any[] = [];
  const defaultStages = ['Foundation', 'Skill Development', 'Practical Application', 'Professional Readiness', 'Career Growth'];
  if (milestonesBlock) {
    const rawItems = milestonesBlock.split(/(?=\d+\.|\n- )/);
    rawItems.forEach((item, index) => {
      const clean = item.replace(/^[\d\.\-\* ]+/, '').trim();
      if (clean) {
        const parts = clean.split(/[-–:]/);
        const title = parts[0]?.trim() || `Milestone Phase ${index + 1}`;
        const desc = parts.slice(1).join(' - ').trim() || 'Key competency checkpoint in your roadmap.';
        const stage = defaultStages[Math.min(index, defaultStages.length - 1)];
        milestones.push({
          id: `m-${index + 1}`,
          title: title.replace(/\*\*/g, ''),
          description: desc.replace(/\*\*/g, ''),
          stage,
          priority: index === 0 ? 'high' : 'medium',
          estimatedDuration: `${(index + 1) * 3} weeks`,
          targetDate: `Month ${index + 1}`,
          completed: index === 0,
        });
      }
    });
  }

  // Fallback if milestones empty
  if (milestones.length === 0) {
    milestones.push(
      { id: 'm-1', title: 'Foundational Knowledge & Mindset', stage: 'Foundation', priority: 'high', estimatedDuration: '3 weeks', targetDate: 'Month 1', completed: true },
      { id: 'm-2', title: 'Applied Competency & Hands-on Tools', stage: 'Skill Development', priority: 'high', estimatedDuration: '4 weeks', targetDate: 'Month 2', completed: false },
      { id: 'm-3', title: 'Capstone Portfolio Project', stage: 'Practical Application', priority: 'medium', estimatedDuration: '4 weeks', targetDate: 'Month 3', completed: false }
    );
  }

  // 5. Parse Tasks
  const tasks: any[] = [];
  if (tasksBlock) {
    const rawTasks = tasksBlock.split(/\n/).map((l) => l.trim()).filter((l) => l.startsWith('-') || /^\d+\./.test(l));
    rawTasks.forEach((t, i) => {
      const clean = t.replace(/^[\d\.\-\* ]+/, '').trim().replace(/\*\*/g, '');
      if (clean) {
        tasks.push({
          id: `t-${i + 1}`,
          title: clean,
          category: i % 2 === 0 ? 'Technical' : 'Portfolio',
          priority: i < 3 ? 'high' : 'medium',
          dueDate: `Week ${Math.floor(i / 2) + 1}`,
          completed: i === 0,
        });
      }
    });
  }

  if (tasks.length === 0) {
    tasks.push(
      { id: 't-1', title: 'Audit current baseline skills and create study calendar', category: 'Foundation', priority: 'high', dueDate: 'This week', completed: true },
      { id: 't-2', title: 'Build first hands-on problem prototype without tutorials', category: 'Technical', priority: 'high', dueDate: 'Next week', completed: false },
      { id: 't-3', title: 'Document capstone architecture and publish README spec', category: 'Portfolio', priority: 'medium', dueDate: 'In 2 weeks', completed: false }
    );
  }

  // 6. Parse Habits
  const habits: any[] = [];
  if (habitsBlock) {
    const rawHabits = habitsBlock.split(/\n/).map((l) => l.trim()).filter((l) => l.startsWith('-') || /^\d+\./.test(l));
    rawHabits.forEach((h, i) => {
      const clean = h.replace(/^[\d\.\-\* ]+/, '').trim().replace(/\*\*/g, '');
      if (clean) {
        habits.push({
          id: `h-${i + 1}`,
          title: clean,
          frequency: 'daily',
          targetDaysPerWeek: 5,
          currentStreak: i === 0 ? 3 : 1,
          bestStreak: 7,
          completedToday: i === 0,
          category: 'Skill',
        });
      }
    });
  }

  if (habits.length === 0) {
    habits.push(
      { id: 'h-1', title: '45 mins focused deliberate skill practice', frequency: 'daily', targetDaysPerWeek: 5, currentStreak: 3, bestStreak: 7, completedToday: true, category: 'Skill' },
      { id: 'h-2', title: 'Read 1 industry case study or technical reference doc', frequency: 'daily', targetDaysPerWeek: 4, currentStreak: 2, bestStreak: 5, completedToday: false, category: 'Knowledge' }
    );
  }

  const parsedPlan = {
    schemaVersion: 'foyc_handoff_v1',
    profile: userProfile || {},
    reflection: userReflection || {},
    direction: {
      primaryTitle,
      summary,
      whyRecommended,
      longTermGoal,
      shortTermObjective,
      alternativeTitles: alternativeTitles.length ? alternativeTitles : ['Adjacent Specialist', 'Domain Lead'],
      strengths: strengths.length ? strengths : ['Analytical problem solving', 'High adaptability'],
      skillGaps: skillGaps.length ? skillGaps : ['Advanced architecture', 'Production deployment'],
      reassessmentQuestions: [
        'Am I still excited by the day-to-day problems in this field?',
        'Did I hit my weekly consistency targets for the last 14 days?',
      ],
      assumptions: [
        'User can dedicate 10-15 focused hours per week.',
        'Learning will focus on building verifiable proof of work.',
      ],
      lastReassessedDate: 'Just now',
    },
    milestones,
    tasks,
    habits,
    projects: [
      {
        id: 'p-1',
        title: 'End-to-End Problem Solver Showcase',
        description: 'A realistic, full-scope capstone addressing a genuine customer dilemma.',
        skillsDeveloped: ['Architecture', 'Implementation', 'Testing'],
        status: 'in-progress',
        targetDate: 'Month 2',
        projectUrl: 'https://github.com/example/capstone',
        achievements: ['Working prototype deployed', 'Documentation completed'],
      },
    ],
    resources: [
      { id: 'r-1', title: 'Official Documentation & Standards Guide', type: 'Documentation', provider: 'Official Docs', url: 'https://developer.mozilla.org', isVerified: true, isFree: true },
      { id: 'r-2', title: 'Core Industry Guided Track', type: 'Course', provider: 'Community Educators', url: 'https://roadmap.sh', isVerified: true, isFree: true },
    ],
  };

  res.json({
    success: true,
    data: parsedPlan,
    message: 'Handoff parsed and validated successfully against foyc_handoff_v1.',
  });
};
