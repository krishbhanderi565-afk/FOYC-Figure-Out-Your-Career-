import {
  CareerDashboardData,
  CareerDirection,
  Milestone,
  TaskItem,
  HabitItem,
  ProjectItem,
  ResourceItem,
  UserProfile,
  UserReflection
} from '../types/career';

/**
 * Extracts content between marker tags like ---BEGIN FOYC TAG--- and ---END FOYC TAG---
 */
function extractSection(text: string, tag: string): string | null {
  const regex = new RegExp(`---BEGIN FOYC ${tag}---([\\s\\S]*?)---END FOYC ${tag}---`, 'i');
  const match = text.match(regex);
  return match ? match[1].trim() : null;
}

export interface ParseResult {
  success: boolean;
  data?: Partial<CareerDashboardData>;
  errors: string[];
  warnings: string[];
}

export function parseHandoffText(
  pastedText: string,
  existingProfile: UserProfile,
  existingReflection: UserReflection
): ParseResult {
  const errors: string[] = [];
  const warnings: string[] = [];

  if (!pastedText || pastedText.trim().length < 50) {
    return {
      success: false,
      errors: ['Input too short. Please paste the full FOYC Handoff generated by ChatGPT.'],
      warnings: [],
    };
  }

  // Check section markers
  const dirBlock = extractSection(pastedText, 'CAREER DIRECTION');
  const roadmapBlock = extractSection(pastedText, 'SKILL ROADMAP');
  const milestonesBlock = extractSection(pastedText, 'MILESTONES');
  const tasksBlock = extractSection(pastedText, 'TASKS');
  const habitsBlock = extractSection(pastedText, 'HABITS');
  const projectsBlock = extractSection(pastedText, 'PROJECTS');
  const resourcesBlock = extractSection(pastedText, 'RESOURCES');
  const assumptionsBlock = extractSection(pastedText, 'ASSUMPTIONS');

  if (!dirBlock && !roadmapBlock && !tasksBlock) {
    return {
      success: false,
      errors: [
        'Could not find standard FOYC handoff markers (e.g. ---BEGIN FOYC CAREER DIRECTION---).',
        'Make sure to request ChatGPT to "create your personalized FOYC Career Dashboard Handoff Prompt" and copy the entire response.',
      ],
      warnings: [],
    };
  }

  // Parse Career Direction
  let primaryTitle = 'Modern Career Explorer';
  let summary = 'A customized development plan designed around your natural strengths and interests.';
  let matchReason = 'High alignment with your problem-solving interests and preferred autonomy.';
  let longTermGoal = 'Achieve professional mastery and financial independence in 2-3 years.';
  let shortTermObjective = 'Master fundamental core competencies within the next 90 days.';
  const alternativeTitles: string[] = [];
  const strengths: string[] = [];
  const existingSkills: string[] = [];
  const skillGaps: string[] = [];

  if (dirBlock) {
    const lines = dirBlock.split('\n').map((l) => l.trim()).filter(Boolean);
    for (const line of lines) {
      if (line.toLowerCase().startsWith('primary:') || line.toLowerCase().startsWith('primary direction:') || line.toLowerCase().startsWith('primary career:')) {
        primaryTitle = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (line.toLowerCase().startsWith('summary:') || line.toLowerCase().startsWith('overview:')) {
        summary = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (line.toLowerCase().startsWith('why:') || line.toLowerCase().startsWith('reason:') || line.toLowerCase().startsWith('match reason:')) {
        matchReason = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (line.toLowerCase().startsWith('long-term goal:') || line.toLowerCase().startsWith('long term:')) {
        longTermGoal = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (line.toLowerCase().startsWith('short-term objective:') || line.toLowerCase().startsWith('short term:')) {
        shortTermObjective = line.split(':')[1].trim().replace(/\*\*/g, '');
      } else if (line.toLowerCase().startsWith('alternative:') || line.toLowerCase().startsWith('alternatives:')) {
        const alts = line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, ''));
        alternativeTitles.push(...alts);
      } else if (line.toLowerCase().startsWith('strengths:')) {
        const str = line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, ''));
        strengths.push(...str);
      } else if (line.toLowerCase().startsWith('gaps:') || line.toLowerCase().startsWith('skill gaps:')) {
        const gaps = line.split(':')[1].split(',').map((s) => s.trim().replace(/\*\*/g, ''));
        skillGaps.push(...gaps);
      }
    }
  }

  // Parse Milestones
  const milestones: Milestone[] = [];
  const defaultStages: Milestone['stage'][] = [
    'Foundation',
    'Skill Development',
    'Practical Application',
    'Professional Readiness',
    'Career Growth',
  ];

  if (milestonesBlock) {
    const rawItems = milestonesBlock.split(/(?=\d+\.|\n- )/);
    rawItems.forEach((item, index) => {
      const clean = item.replace(/^[\d\.\-\* ]+/, '').trim();
      if (clean) {
        const parts = clean.split(/[-–:]/);
        const title = parts[0]?.trim() || `Milestone Phase ${index + 1}`;
        const desc = parts.slice(1).join(' - ').trim() || 'Key competency checkpoint in your career journey.';
        const stageIndex = Math.min(index, defaultStages.length - 1);
        milestones.push({
          id: `m-${index + 1}`,
          title: title.replace(/\*\*/g, ''),
          description: desc.replace(/\*\*/g, ''),
          priority: index === 0 ? 'high' : index === 1 ? 'medium' : 'low',
          stage: defaultStages[stageIndex],
          estimatedDuration: `${(index + 1) * 3} weeks`,
          targetDate: `Month ${index + 1}`,
          completed: index === 0,
          associatedTasksCount: 3,
        });
      }
    });
  }

  // Fallback default milestones if block was sparse
  if (milestones.length === 0) {
    warnings.push('Milestones section parsed with defaults.');
    milestones.push(
      {
        id: 'm-1',
        title: 'Core Fundamentals & Mindset Clarity',
        description: 'Solidify foundational concepts and eliminate initial knowledge barriers.',
        priority: 'high',
        stage: 'Foundation',
        estimatedDuration: '3 weeks',
        targetDate: 'Month 1',
        completed: true,
        associatedTasksCount: 4,
      },
      {
        id: 'm-2',
        title: 'Hands-on Competency & Tooling Proficiency',
        description: 'Complete hands-on exercises and build real confidence in practical execution.',
        priority: 'high',
        stage: 'Skill Development',
        estimatedDuration: '4 weeks',
        targetDate: 'Month 2',
        completed: false,
        associatedTasksCount: 5,
      },
      {
        id: 'm-3',
        title: 'Signature Capstone Project Portfolio',
        description: 'Develop and publish end-to-end demonstrable work that proves your skills.',
        priority: 'medium',
        stage: 'Practical Application',
        estimatedDuration: '5 weeks',
        targetDate: 'Month 3',
        completed: false,
        associatedTasksCount: 3,
      },
      {
        id: 'm-4',
        title: 'Industry Positioning & Outreach Launch',
        description: 'Refine professional narrative, resume, LinkedIn and initiate career opportunities.',
        priority: 'medium',
        stage: 'Professional Readiness',
        estimatedDuration: '3 weeks',
        targetDate: 'Month 4',
        completed: false,
        associatedTasksCount: 3,
      }
    );
  }

  // Parse Tasks
  const tasks: TaskItem[] = [];
  if (tasksBlock) {
    const rawTasks = tasksBlock.split(/\n/).map((l) => l.trim()).filter((l) => l.startsWith('-') || /^\d+\./.test(l));
    rawTasks.forEach((t, i) => {
      const clean = t.replace(/^[\d\.\-\* ]+/, '').trim().replace(/\*\*/g, '');
      if (clean) {
        tasks.push({
          id: `t-${i + 1}`,
          title: clean,
          category: i % 2 === 0 ? 'Technical' : i % 3 === 0 ? 'Portfolio' : 'Foundation',
          priority: i < 3 ? 'high' : 'medium',
          dueDate: `Week ${Math.floor(i / 2) + 1}`,
          completed: i === 0,
        });
      }
    });
  }

  if (tasks.length === 0) {
    tasks.push(
      { id: 't-1', title: 'Audit current technical baseline & identify top 3 learning gaps', category: 'Foundation', priority: 'high', dueDate: 'This week', completed: true },
      { id: 't-2', title: 'Set up focused development environment and bookmark primary docs', category: 'Foundation', priority: 'high', dueDate: 'In 3 days', completed: false },
      { id: 't-3', title: 'Complete first 10 structured practical exercises without tutorials', category: 'Technical', priority: 'high', dueDate: 'Next week', completed: false },
      { id: 't-4', title: 'Scope mini-project 1 architecture and write README spec', category: 'Portfolio', priority: 'medium', dueDate: 'In 2 weeks', completed: false },
      { id: 't-5', title: 'Conduct 1 informational conversation with an active practitioner', category: 'Networking', priority: 'low', dueDate: 'In 3 weeks', completed: false },
    );
  }

  // Parse Habits
  const habits: HabitItem[] = [];
  if (habitsBlock) {
    const rawHabits = habitsBlock.split(/\n/).map((l) => l.trim()).filter((l) => l.startsWith('-') || /^\d+\./.test(l));
    rawHabits.forEach((h, i) => {
      const clean = h.replace(/^[\d\.\-\* ]+/, '').trim().replace(/\*\*/g, '');
      if (clean) {
        habits.push({
          id: `h-${i + 1}`,
          title: clean,
          frequency: 'daily',
          targetDaysPerWeek: 5,
          currentStreak: Math.floor(Math.random() * 4) + 1,
          bestStreak: 7,
          completedToday: i % 2 === 0,
          history: { '2026-11-12': true, '2026-11-13': i % 2 === 0 },
          category: 'Execution',
        });
      }
    });
  }

  if (habits.length === 0) {
    habits.push(
      { id: 'h-1', title: '45 mins deep focused skill practice', frequency: 'daily', targetDaysPerWeek: 5, currentStreak: 3, bestStreak: 8, completedToday: true, history: { '2026-11-12': true, '2026-11-13': true }, category: 'Skill' },
      { id: 'h-2', title: 'Read 1 industry case study or technical documentation', frequency: 'daily', targetDaysPerWeek: 4, currentStreak: 2, bestStreak: 5, completedToday: false, history: { '2026-11-12': true, '2026-11-13': false }, category: 'Knowledge' },
      { id: 'h-3', title: 'Document 1 learning takeaway or code snippet daily', frequency: 'daily', targetDaysPerWeek: 5, currentStreak: 4, bestStreak: 6, completedToday: true, history: { '2026-11-12': true, '2026-11-13': true }, category: 'Reflection' },
    );
  }

  // Parse Projects
  const projects: ProjectItem[] = [];
  if (projectsBlock) {
    const rawProjects = projectsBlock.split(/(?=\d+\.|\n- )/);
    rawProjects.forEach((p, i) => {
      const clean = p.replace(/^[\d\.\-\* ]+/, '').trim().replace(/\*\*/g, '');
      if (clean) {
        projects.push({
          id: `p-${i + 1}`,
          title: clean.slice(0, 50),
          description: clean.slice(0, 160),
          skillsDeveloped: ['Core Logic', 'Practical Application'],
          status: i === 0 ? 'in-progress' : 'planned',
          targetDate: `Month ${i + 2}`,
        });
      }
    });
  }

  if (projects.length === 0) {
    projects.push(
      {
        id: 'p-1',
        title: 'End-to-End Problem Solver Showcase',
        description: 'A realistic, full-scope project solving a real user workflow with clean code, testing, and documentation.',
        skillsDeveloped: ['Architecture', 'Implementation', 'Deployment'],
        status: 'in-progress',
        targetDate: 'Month 2',
        projectUrl: 'https://github.com/example/project-one',
        achievements: ['Working prototype completed', 'README documentation drafted'],
      },
      {
        id: 'p-2',
        title: 'Domain Analytics & Integration System',
        description: 'Connecting live external data feeds, processing insights, and displaying visual analytics.',
        skillsDeveloped: ['Data Flow', 'API Integration', 'UI/UX Polish'],
        status: 'planned',
        targetDate: 'Month 3',
      }
    );
  }

  // Resources
  const resources: ResourceItem[] = [
    { id: 'r-1', title: 'Official Core Reference & Documentation', type: 'Documentation', provider: 'Standard Official Docs', url: 'https://developer.mozilla.org', isVerified: true, isFree: true, estimatedHours: 20 },
    { id: 'r-2', title: 'Zero to Mastery Guided Video Track', type: 'Course', provider: 'Top Community Educators', url: 'https://youtube.com', isVerified: true, isFree: true, estimatedHours: 40 },
    { id: 'r-3', title: 'Hands-on Interactive Problem Sandbox', type: 'Practice', provider: 'Interactive Practice Platform', url: 'https://roadmap.sh', isVerified: true, isFree: true, estimatedHours: 15 },
  ];

  const direction: CareerDirection = {
    primaryTitle,
    summary,
    matchReason,
    longTermGoal,
    shortTermObjective,
    alternativeTitles: alternativeTitles.length ? alternativeTitles : ['Technical Product Lead', 'Solutions Architect'],
    strengths: strengths.length ? strengths : ['Structured analytical thinking', 'Perseverance in troubleshooting', 'Rapid learner'],
    existingSkills: existingSkills.length ? existingSkills : ['Basic programming fundamentals', 'Analytical research', 'Communication'],
    skillGaps: skillGaps.length ? skillGaps : ['Advanced system design', 'Production testing and deployment', 'Portfolio presentation'],
    reassessmentQuestions: [
      'Am I enjoying solving these technical problems, or does it feel like pure chore?',
      'Has my weekly consistency stayed above 75% for 3 straight weeks?',
      'Are the projects I am building genuinely exciting to demonstrate to an employer?',
    ],
    assumptions: [
      'User can commit 10-15 focused hours per week.',
      'Goal is direct employment or freelancing within 6-9 months.',
      'AI tools will be used as accelerators rather than crutches.',
    ],
    lastReassessedDate: 'Just now',
  };

  const parsedData: CareerDashboardData = {
    profile: existingProfile,
    reflection: existingReflection,
    direction,
    milestones,
    tasks,
    habits,
    projects,
    resources,
  };

  return {
    success: true,
    data: parsedData,
    errors,
    warnings,
  };
}
